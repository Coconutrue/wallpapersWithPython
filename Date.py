import datetime


class Date:
    """Класс для работы с датой и временем"""

    @staticmethod
    def getDay():
        """
        Возвращает название текущего дня недели на русском языке
        Пример: 'Понедельник', 'Вторник' и т.д.
        """
        # Список дней недели на русском (начинается с понедельника)
        days = [
            'Понедельник', 'Вторник', 'Среда', 'Четверг',
            'Пятница', 'Суббота', 'Воскресенье'
        ]
        # isoweekday() возвращает 1-7 (пн-вс), вычитаем 1 для индексации списка
        return days[datetime.datetime.today().isoweekday() - 1]

    @staticmethod
    def get(*formats):
        """
        Возвращает текущую дату/время в указанном формате(ах)

        Примеры использования:
        get('%H:%M') -> '14:30' (только время)
        get('%d.%m.%Y') -> '15.05.2026' (только дата)
        get('%H:%M', '%d.%m.%Y') -> ('14:30', '15.05.2026') (кортеж)

        formats - один или несколько форматов strftime
        """
        # Получаем текущий момент времени
        date = datetime.datetime.now()

        # Если передан только один формат
        if len(formats) == 1:
            return date.strftime(formats[0])

        # Если передано несколько форматов - возвращаем кортеж результатов
        back = []
        for fmt in formats:
            back.append(date.strftime(fmt))
        return tuple(back)