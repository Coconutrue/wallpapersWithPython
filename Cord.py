class Cord:
    """Класс для представления прямоугольной области на экране (координаты и размеры)"""

    def __init__(self, x, y, w, h):
        """
        Конструктор прямоугольной области
        x, y - координаты левого верхнего угла
        w, h - ширина и высота области
        """
        self.x = x  # Левая граница
        self.y = y  # Верхняя граница
        self.w = w  # Ширина
        self.h = h  # Высота
        self.x2 = x + w  # Правая граница (x + ширина)
        self.y2 = y + h  # Нижняя граница (y + высота)

    def isInside(self, x, y):
        """
        Проверяет, находится ли точка (x, y) внутри прямоугольной области
        Возвращает True, если точка внутри, False - если снаружи
        """
        # Проверяем попадание по X и по Y координатам
        return self.x <= x <= self.x2 and self.y <= y <= self.y2