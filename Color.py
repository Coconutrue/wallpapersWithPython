class Color:
    """Класс для работы с цветами и темами оформления"""

    @staticmethod
    def hex(s):
        """
        Преобразует HEX цвет в RGB кортеж
        Пример: hex('#FF0000') -> (255, 0, 0)
        s - строка с HEX цветом (например '#131313')
        """
        # Удаляем символ # и преобразуем из 16-ричной в десятичную систему
        n = int(s.lstrip('#'), 16)
        # Извлекаем компоненты RGB через битовые операции
        # >> - сдвиг вправо, & - побитовое И для маски
        return (n >> 16,  # Красный компонент (первые 2 hex цифры)
                (n >> 8) & 0xff,  # Зеленый компонент (средние 2 hex цифры)
                n & 0xff)  # Синий компонент (последние 2 hex цифры)

    @staticmethod
    def getThemeList():
        return [
            # Тема 0: Темно-красная (готическая)
            {'bg': Color.hex('#131313'),  # Фон - темно-серый
             'fg': Color.hex('#980002'),  # Основной цвет - темно-красный
             'text': Color.hex('#ffbf00')},  # Текст - золотистый

            # Тема 1: Бежево-коричневая (классическая)
            {'bg': Color.hex('#ebdcb2'),  # Фон - бежевый
             'fg': Color.hex('#af4425'),  # Основной цвет - терракотовый
             'text': Color.hex('#552e1c')},  # Текст - темно-коричневый

            # Тема 2: Бордовая (винная)
            {'bg': Color.hex('#1e0000'),  # Фон - почти черный с красным оттенком
             'fg': Color.hex('#bc6d4f'),  # Основной цвет - кирпичный
             'text': Color.hex('#9d331f')},  # Текст - красновато-коричневый

            # Тема 3: Морская (бирюзовая)
            {'bg': Color.hex('#003b46'),  # Фон - темно-бирюзовый
             'fg': Color.hex('#c3dfe6'),  # Основной цвет - бледно-голубой
             'text': Color.hex('#66a5ad')}  # Текст - бирюзовый
        ]

    @classmethod
    def getTheme(cls, mode):
        """
        Возвращает тему по индексу с защитой от выхода за границы
        mode - индекс темы (0, 1, 2, 3, 4)
        """
        themes = cls.getThemeList()
        # mode % len(themes) - циклический перебор тем (если индекс больше 4, начинаем с 0)
        return themes[mode % len(themes)]
